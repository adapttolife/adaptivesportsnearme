"""Build the sport figures' motion for the site.

    python3 scripts/motion/build.py          # writes public/emblems/motion/*.json and public/app/motion-index.js

Each spec in specs/ says which of a drawing's own shapes move together, where each
group turns and its keyframes (see README.md). This writes one small JSON file per
drawing that public/app/motion.js plays, and the index that maps every sport key
(including the sports that share a drawing) to its file. Nothing is redrawn."""
import hashlib, importlib, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path[:0] = [str(HERE / "lib"), str(HERE / "specs")]
import mv

OUT = mv.ROOT / "public" / "emblems" / "motion"
INDEX = mv.ROOT / "public" / "app" / "motion-index.js"
MODULES = ["pilots", "b1", "b2", "b3", "b4", "b5", "b6", "b7"]

def used(tree, cuts, out):
    for n in tree:
        if n[0] == "p": out += list(n[1])
        elif n[0] in ("bend", "joint"): out.append(n[2])
        elif n[0] in ("cut", "clip"): cuts.add(n[1])
        else: used(n[2], cuts, out)
    return out

def main():
    specs = [s for m in MODULES for s in importlib.import_module(m).SPECS]
    OUT.mkdir(parents=True, exist_ok=True)
    files, problems = {}, []
    for s in specs:
        drawing = s.get("drawing", s["key"])
        cuts = set(); ids = used(s["tree"], cuts, []) + sorted(cuts)
        have = sorted(mv.load(drawing))
        if sorted(ids) != have:          # every shape of the drawing, each exactly once
            problems.append(f"{s['key']}: shapes used {sorted(ids)} != drawing {have}")
        for cls, keys in s.get("keys", {}).items():   # a group that turns or scales needs its pivot
            if any(f in str(k[1]) for k in keys for f in ("rotate", "scale")) and cls not in s.get("origins", {}):
                problems.append(f"{s['key']}: group '{cls}' turns or scales but has no origin")
        data = mv.build(s)
        text = json.dumps(data, separators=(",", ":"))
        (OUT / f"{drawing}.json").write_text(text + "\n")
        files[drawing] = hashlib.sha256(text.encode()).hexdigest()[:10]
    # Every sport key gets a file: its own drawing, or the drawing it shares (README table).
    sources = [l.split("\t") for l in (mv.SPORTS / "SOURCES.tsv").read_text().strip().split("\n")[1:]]
    by_hash = {mv.drawing_hash(d): d for d in files}
    index = {}
    for key, *_ in sources:
        d = by_hash.get(mv.drawing_hash(key))
        if not d: problems.append(f"{key}: no motion for its drawing"); continue
        index[key] = f"{d}.json?v={files[d]}"
    stale = sorted(p.stem for p in OUT.glob("*.json") if p.stem not in files)
    for name in stale: (OUT / f"{name}.json").unlink()
    INDEX.write_text("// Generated by scripts/motion/build.py. Do not edit: change a spec and rebuild.\n"
                     "// Every sport key -> its drawing's motion file in /emblems/motion (shared drawings share a file).\n"
                     f"export const MOTION = {json.dumps(index, indent=0, sort_keys=True)};\n")
    size = sum((OUT / f"{d}.json").stat().st_size for d in files)
    print(f"{len(files)} drawings, {len(index)} sport keys, {size // 1024} KB" + (f", removed {stale}" if stale else ""))
    if problems:
        print("\n".join(problems)); sys.exit(1)

if __name__ == "__main__":
    main()
