// Writes public/app/icons.js: only the Lucide icons the site's app uses, so a phone
// downloads about 6 KB instead of the whole 109 KB library before the page can draw.
// Icons come unchanged from the vendored library (public/assets/vendor/lucide-1.49.0.min.js,
// ISC license). Run after adding an icon name to public/app:
//   node scripts/build-app-icons.mjs
// test/icons.test.js fails when a name the app uses is missing from icons.js.
import { readFileSync, readdirSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import vm from "vm";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(root + p, "utf8");

// The same patterns test/icons.test.js uses to find every icon name the app passes.
export const ICON_NAME_PATTERNS = [
  /\bicon\(\s*"([a-z0-9-]+)"/g,
  /\bicon\([^()"]*\?\s*"([a-z0-9-]+)"\s*:\s*"([a-z0-9-]+)"/g,
  /\b(?:ic|icon):\s*"([a-z0-9-]+)"/g,
  /\bitem\("[^"]*",\s*[^,]+,\s*"([a-z0-9-]+)",/g,
  /\["(?:is-[a-z]+)?",\s*"([a-z0-9-]+)",/g,
  /\brow\(`[^`]*`,\s*"([a-z0-9-]+)",/g,
  /\blink\(`[^`]*`,[^;]*?,\s*"([a-z0-9-]+)"\)/g,
];
export function appIconNames() {
  const files = ["public/app/app.js", ...readdirSync(root + "public/app/views").filter((f) => f.endsWith(".js")).map((f) => "public/app/views/" + f)];
  const names = new Set();
  for (const f of files) { const src = read(f); for (const re of ICON_NAME_PATTERNS) for (const m of src.matchAll(re)) for (const n of m.slice(1)) if (n) names.add(n); }
  return [...names].sort();
}
export const pascal = (name) => String(name).split("-").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");
export function vendorIcons() {
  const context = vm.createContext({ console, document: { querySelectorAll: () => [], createElementNS: () => ({}) }, MutationObserver: class { observe() {} } });
  vm.runInContext(read("public/assets/vendor/lucide-1.49.0.min.js"), context);
  return context.lucide.icons;
}
export function buildIconsModule() {
  const lib = vendorIcons(), out = {}, missing = [];
  for (const n of appIconNames()) { const k = pascal(n); if (lib[k]) out[k] = lib[k]; else missing.push(n); }
  if (missing.length) throw new Error("not in Lucide 1.49.0: " + missing.join(", "));
  return `// Generated by scripts/build-app-icons.mjs. Do not edit; run the script after adding an icon.\n` +
    `// From Lucide v1.49.0 (ISC license, public/assets/vendor/lucide-1.49.0.min.js), unchanged.\n` +
    `export const ICONS = ${JSON.stringify(out)};\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const js = buildIconsModule();
  writeFileSync(root + "public/app/icons.js", js);
  console.log(`public/app/icons.js: ${Object.keys(JSON.parse(js.slice(js.indexOf("{"), js.lastIndexOf("}") + 1))).length} icons, ${js.length} bytes`);
}
