"""Everything on the site that shows the Adapt To Life mark, built from the official file.

  /tmp/pv/bin/python scripts/icons/brand.py            # write the files below
  /tmp/pv/bin/python scripts/icons/brand.py --figure   # print figure.OFFICIAL from the same file

Source: brand/090226_AdaptToLife_Icon.svg (brand identity of 2 Sep 2026; Drive:
Logos / FINAL Logo). Charcoal #3B3B46, coral #FF5C39 (the athlete's leg). Writes:

- public/favicon.svg: the mark in brand colours; light ink on dark browser chrome.
- public/favicon-32.png: the mark on transparent, 32 px.
- public/apple-touch-icon.png, icon-192.png, icon-512.png: the mark on the app's
  cream (#F8F5F0, the manifest background), about 72% wide, inside the maskable safe zone.
- public/emblems/adaptive.svg: the generic listing stamp, the mark in one ink
  (#1A1A1A) on the sport icons' 120 grid.

The old drawing (atl-logo-2026, Jul 31) is retired: nothing here may use it.
"""
import os, re, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "brand", "090226_AdaptToLife_Icon.svg")
CHARCOAL, CORAL, CREAM, INK, LIGHT = "#3B3B46", "#FF5C39", "#F8F5F0", "#1A1A1A", "#F5F5F3"


def mark():
    """[(cls, d)] in the official file's order and its viewBox width/height."""
    s = open(SRC).read()
    w, h = [float(v) for v in re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', s).group(1, 2)]
    paths = [(m.group(1), m.group(2)) for m in re.finditer(r'<path class="(st\d)" d="([^"]+)"', s)]
    assert len(paths) == 5, "the official icon changed shape: check brand.py and figure.OFFICIAL"
    return paths, w, h


def svg_doc(paths, w, h, side, colours, extra_css="", pad=0.0):
    """Square SVG with the mark centred; colours maps st0/st1 to a fill."""
    box = max(w, h) / (1 - 2 * pad)
    x0, y0 = (w - box) / 2, (h - box) / 2
    css = "".join(f".{k}{{fill:{v}}}" for k, v in colours.items()) + extra_css
    body = "".join(f'<path class="{c}" d="{d}"/>' for c, d in paths)
    size = f' width="{side}" height="{side}"' if side else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0:.2f} {y0:.2f} {box:.2f} {box:.2f}"{size}>'
            f'<style>{css}</style>{body}</svg>\n')


def png(svg_text, side, out, bg=None):
    with tempfile.TemporaryDirectory() as t:
        f = os.path.join(t, "m.svg")
        open(f, "w").write(svg_text)
        cmd = ["rsvg-convert", "-w", str(side), "-h", str(side), f, "-o", out]
        if bg:
            cmd[1:1] = ["-b", bg]
        subprocess.run(cmd, check=True)


def write():
    paths, w, h = mark()
    brand = {"st1": CHARCOAL, "st0": CORAL}
    pub = os.path.join(ROOT, "public")
    open(os.path.join(pub, "favicon.svg"), "w").write(
        "<!-- The Adapt To Life mark (brand identity, 2 Sep 2026). Generated by scripts/icons/brand.py. -->\n"
        + svg_doc(paths, w, h, None, brand, f"@media (prefers-color-scheme:dark){{.st1{{fill:{LIGHT}}}}}"))
    png(svg_doc(paths, w, h, 32, brand, pad=0.05), 32, os.path.join(pub, "favicon-32.png"))
    for name, side in (("apple-touch-icon.png", 180), ("icon-192.png", 192), ("icon-512.png", 512)):
        png(svg_doc(paths, w, h, side, brand, pad=0.14), side, os.path.join(pub, name), bg=CREAM)
    stamp = svg_doc(paths, w, h, None, {"st1": INK, "st0": INK}, pad=0.08)
    stamp = stamp.replace('<svg xmlns="http://www.w3.org/2000/svg" ',
                          '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" ')
    open(os.path.join(pub, "emblems", "adaptive.svg"), "w").write(
        "<!-- Generic listing stamp: the Adapt To Life mark in one ink. Generated by scripts/icons/brand.py. -->\n" + stamp)
    print("wrote favicon.svg, favicon-32.png, apple-touch-icon.png, icon-192.png, icon-512.png, emblems/adaptive.svg")


def figure_parts():
    """The athlete's parts in figure space (wheel outer circle r 20.4 at (0, -0.4)), for figure.OFFICIAL."""
    sys.path.insert(0, HERE)
    import kit
    paths, w, h = mark()
    P = [kit.svg(d) for _, d in paths]
    A, LEG, HEAD, TORSO, WHEEL = P
    x0, y0, x1, y1 = WHEEL.bounds
    R = (x1 - x0) / 2
    cx, cy = (x0 + x1) / 2, y1 - R          # outer circle from its left, right and bottom extremes
    sc = 20.4 / R
    tof = lambda p: kit.xf(p, sc, 0, 0, sc, -cx * sc, -cy * sc - 0.4)
    parts = dict(head=tof(HEAD), torso=tof(TORSO), leg=tof(LEG), wheel=tof(WHEEL))
    print("OFFICIAL = {")
    for k in ("head", "torso", "leg", "wheel"):
        print(f'    "{k}": "{kit._d(parts[k], 3)}",')
    print("}")


if __name__ == "__main__":
    figure_parts() if "--figure" in sys.argv else write()
