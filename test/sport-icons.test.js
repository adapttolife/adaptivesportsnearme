// The sport icons (public/emblems/sports/<key>.svg) are Alec's drawings as vectors,
// synced unchanged from Google Drive (Website / ASNM Flat Vector Logo / SVGs) by
// scripts/sport-icons-sync.py. These checks hold the folder to that contract, so a
// hand edit, a missing sport or a stray file fails here, not on a page.
import { test } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";

const dir = new URL("../public/emblems/sports/", import.meta.url);
const files = readdirSync(dir);
const icons = files
  .filter((f) => f.endsWith(".svg"))
  .map((f) => [f.slice(0, -4), readFileSync(new URL(f, dir), "utf8")]);
const sources = readFileSync(new URL("SOURCES.tsv", dir), "utf8")
  .trim()
  .split(/\r?\n/)
  .slice(1)
  .map((l) => l.split("\t"));
const drawing = (svg) =>
  [...svg.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]).join("");

test("one icon per sport key, each an SVG and a PNG, nothing extra", () => {
  assert.equal(icons.length, 47, `${icons.length} icons`);
  const keys = icons.map(([k]) => k).sort();
  assert.deepEqual(
    files
      .filter((f) => f.endsWith(".png"))
      .map((f) => f.slice(0, -4))
      .sort(),
    keys,
  );
  assert.deepEqual(sources.map(([k]) => k).sort(), keys);
});

test("every icon is Alec's Drive file, unchanged, and a clean one-colour vector", () => {
  const byKey = Object.fromEntries(icons);
  for (const [key, drive, sha] of sources) {
    const svg = byKey[key];
    assert.equal(
      createHash("sha256").update(svg.replace(/\r\n/g, "\n")).digest("hex"),
      sha,
      `${key}: differs from ${drive} in Drive`,
    );
    assert.match(
      svg,
      /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 512 512"/,
      key,
    );
    assert.match(svg, /<title>[^<]+<\/title>/, `${key}: needs a title`);
    assert.ok(
      !/<script|<image|<foreignObject|<style|href=|url\(|@import/i.test(svg),
      `${key}: no scripts, styles, images or outside references`,
    );
    for (const [, fill] of svg.matchAll(/fill="([^"]+)"/g))
      assert.equal(fill, "currentColor", `${key}: one colour`);
    assert.ok(svg.length < 32 * 1024, `${key}: ${svg.length} bytes`);
  }
});

test("sports that share a drawing each keep their own file, titled for the sport", () => {
  const byKey = Object.fromEntries(icons);
  const shared = {
    "equine-therapy": "equestrian",
    equestrianvaulting: "equestrian",
    blindsports: "goalball",
    handcycling: "cycling",
    surfing: "multi",
    wheelchairracing: "trackfield",
  };
  for (const [key, base] of Object.entries(shared)) {
    assert.equal(
      drawing(byKey[key]),
      drawing(byKey[base]),
      `${key} should use ${base}'s drawing`,
    );
    assert.notEqual(
      byKey[key],
      byKey[base],
      `${key} is its own file (its own title)`,
    );
  }
});

test("the site's mark is the official logo (2 Sep 2026), never the retired draft", () => {
  const official = readFileSync(
    new URL(
      "../scripts/icons/brand/090226_AdaptToLife_Icon.svg",
      import.meta.url,
    ),
    "utf8",
  );
  const firstPath = official.match(/<path class="st1" d="([^"]{40})/)[1];
  for (const f of ["favicon.svg", "emblems/adaptive.svg"]) {
    const svg = readFileSync(
      new URL(`../public/${f}`, import.meta.url),
      "utf8",
    );
    assert.ok(
      svg.includes(firstPath),
      `${f} is not drawn from the official mark`,
    );
    assert.ok(
      svg.includes("Generated by scripts/icons/brand.py"),
      `${f} was edited by hand`,
    );
    assert.ok(
      !svg.includes("M359.579 1424.07"),
      `${f} still carries the retired drawing`,
    );
  }
  const fav = readFileSync(
    new URL("../public/favicon.svg", import.meta.url),
    "utf8",
  );
  assert.ok(
    fav.includes("#3B3B46") && fav.includes("#FF5C39"),
    "favicon keeps the brand charcoal and coral",
  );
});
