// The sport icons (public/emblems/sports/<key>.svg) are Alec's drawings traced by
// scripts/icons/trace.py. These checks hold every file to the shape the tracer
// writes, so a hand edit or a bad export fails here, not on a page.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";

const dir = new URL("../public/emblems/sports/", import.meta.url);
const icons = readdirSync(dir).filter((f) => f.endsWith(".svg")).map((f) => [f.slice(0, -4), readFileSync(new URL(f, dir), "utf8")]);

test("every sport icon is one clean path on the 512 grid", () => {
  assert.ok(icons.length >= 47, `only ${icons.length} icons`);
  for (const [key, svg] of icons) {
    assert.match(svg, /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 512 512" role="img"><title>[^<]+<\/title><path fill="currentColor" d="M[^"]+"\/><\/svg>\n$/, key);
    assert.ok(svg.length < 40 * 1024, `${key}: ${svg.length} bytes`);
  }
});

test("sport icons are still pictures: no scripts, styles, motion or outside references", () => {
  for (const [key, svg] of icons) {
    assert.ok(!/<script|<style|<image|<foreignObject|@keyframes|animation|href=|url\(/i.test(svg), key);
  }
});

test("the site's mark is the official logo (2 Sep 2026), never the retired draft", () => {
  const official = readFileSync(new URL("../scripts/icons/brand/090226_AdaptToLife_Icon.svg", import.meta.url), "utf8");
  const firstPath = official.match(/<path class="st1" d="([^"]{40})/)[1];
  for (const f of ["favicon.svg", "emblems/adaptive.svg"]) {
    const svg = readFileSync(new URL(`../public/${f}`, import.meta.url), "utf8");
    assert.ok(svg.includes(firstPath), `${f} is not drawn from the official mark`);
    assert.ok(svg.includes("Generated by scripts/icons/brand.py"), `${f} was edited by hand`);
    assert.ok(!svg.includes("M359.579 1424.07"), `${f} still carries the retired drawing`);
  }
  const fav = readFileSync(new URL("../public/favicon.svg", import.meta.url), "utf8");
  assert.ok(fav.includes("#3B3B46") && fav.includes("#FF5C39"), "favicon keeps the brand charcoal and coral");
});
